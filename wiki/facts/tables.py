BANDS = ["D", "C", "B", "A", "AAA"]
YAML_HEADER = "# GENERATED by wiki/facts/build_facts.py — do not edit.\n"
HEADER = "<!-- GENERATED by wiki/facts/build_facts.py — do not edit. -->\n\n"


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def band_table(t: dict[str, str]) -> str:
    return _table(["Band", "n", "Share", "Observed default rate", "Mean predicted PD",
                   "Observed / predicted"],
                  [[b] + [t[f"score.band.{b}.{c}"] for c in
                          ("n", "share", "observed", "predicted", "ratio")] for b in BANDS])


def population_table(t: dict[str, str]) -> str:
    names = {"everyone": "Everyone (the gate)", "booked": "Booked only",
             "rejected": "Rejected only"}
    return _table(["Population", "n", "Default rate", "Held-out AUC"],
                  [[names[p], t[f"score.pop.{p}.n"], t[f"score.pop.{p}.dr"],
                    t[f"score.pop.{p}.auc"]] for p in names])


def stress_table(t: dict[str, str]) -> str:
    return _table(["Scenario", "Columns", "Held-out AUC", "Gate"], [
        ["Committed card", f"all {t['score.n_features']}", t["score.auc_holdout"],
         "pass"],
        ["Bureau feed down", "drop " + t["score.stress.bureau_columns"],
         t["score.stress.no_bureau.auc"],
         "pass" if float(t["score.stress.no_bureau.auc"]) >= float(t["score.gate"]) else "**fail**"],
        ["Five raw columns", t["score.stress.five_raw_columns"], t["score.stress.five_raw.auc"],
         "pass" if float(t["score.stress.five_raw.auc"]) >= float(t["score.gate"]) else "**fail**"],
        ["Structural zeros only", t["score.stress.structural_five_columns"],
         t["score.stress.structural_five.auc"], "**fail**"],
        ["Revenue proxies only", t["score.stress.proxy_five_columns"],
         t["score.stress.proxy_five.auc"], "**fail**"],
    ])


def iv_table(t: dict[str, str]) -> str:
    feats = sorted((k.split(".", 2)[2] for k in t if k.startswith("score.iv.")),
                   key=lambda c: -float(t[f"score.iv.{c}"]))
    return _table(["Feature", "Information value", "Share of logit variance"],
                  [[f"`{c}`", t[f"score.iv.{c}"], t[f"score.var_share.{c}"]] for c in feats])


